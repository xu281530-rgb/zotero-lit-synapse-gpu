/* eslint-env node */

import { createHash } from "node:crypto";
import {
  copyFile,
  mkdir,
  readFile,
  rm,
  stat,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectDirectory = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const cudaDirectory = path.join(projectDirectory, ".cuda-toolkit", "12.6");
const nativeDirectory = path.join(projectDirectory, "native", "vector-gpu");
const assetDirectory = path.join(projectDirectory, "addon", "native", "gpu");
const generatedManifestPath = path.join(
  projectDirectory,
  "src",
  "modules",
  "semantic",
  "gpuAssetManifest.generated.ts",
);
const expectedCudart = {
  version: "12.6.77",
  size: 556544,
  sha256: "d954ca542b3b6bcf03cc2b798a7d00051501cf734ca751050e986af505cf9dad",
};

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

const sources = [
  {
    name: "LICENSE-NVIDIA-CUDA.txt",
    path: path.join(cudaDirectory, "LICENSE"),
  },
  {
    name: "LICENSE-nlohmann-json.txt",
    path: path.join(
      nativeDirectory,
      "third_party",
      "licenses",
      "nlohmann-json-LICENSE.MIT",
    ),
  },
  {
    name: "cudart64_12.dll",
    path: path.join(cudaDirectory, "bin", "cudart64_12.dll"),
  },
  {
    name: "vector-gpu.exe",
    path: path.join(nativeDirectory, "build", "bin", "vector-gpu.exe"),
  },
];

const sourceContents = new Map();
for (const source of sources) {
  sourceContents.set(source.name, await readFile(source.path));
}

const cudart = sourceContents.get("cudart64_12.dll");
if (
  cudart.length !== expectedCudart.size ||
  sha256(cudart) !== expectedCudart.sha256
) {
  throw new Error(
    `cudart64_12.dll is not the pinned CUDA ${expectedCudart.version} runtime`,
  );
}
const executable = sourceContents.get("vector-gpu.exe");
if (executable.length < 2 || executable[0] !== 0x4d || executable[1] !== 0x5a) {
  throw new Error("vector-gpu.exe is missing or is not a Windows PE executable");
}

const executableHash = sha256(executable);
const manifest = {
  schemaVersion: 1,
  assetVersion: `vector-gpu-1.0.0-cuda${expectedCudart.version}-${executableHash.slice(0, 12)}`,
  protocol: "vector-gpu/1",
  platform: "windows-x64",
  files: [],
};

await rm(assetDirectory, { recursive: true, force: true });
await mkdir(assetDirectory, { recursive: true });
for (const source of sources) {
  const destination = path.join(assetDirectory, source.name);
  await copyFile(source.path, destination);
  const bytes = sourceContents.get(source.name);
  const copied = await stat(destination);
  manifest.files.push({
    name: source.name,
    sha256: sha256(bytes),
    size: copied.size,
  });
}

const manifestBytes = Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(path.join(assetDirectory, "manifest.json"), manifestBytes);
const manifestHash = sha256(manifestBytes);
await writeFile(
  generatedManifestPath,
  `/** Generated by scripts/package-gpu-assets.js. */\nexport const GPU_ASSET_MANIFEST_SHA256 =\n  "${manifestHash}";\n`,
);

console.log(`Packaged ${manifest.files.length} GPU assets`);
console.log(`Asset version: ${manifest.assetVersion}`);
console.log(`Manifest SHA-256: ${manifestHash}`);
